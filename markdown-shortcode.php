<?php
/*
Plugin Name: Markdown Shortcode
Description: damn simple [markdown]#via shortcode[/markdown], uses parsedown (parsedown.org) and highlight.js (highlightjs.org)
Version:     0.2.5
Author:      Johannes Hoppe
Author URI:  http://haushoppe-its.de
*/

register_activation_hook(__FILE__, array('Markdown_Shortcode_Plugin', 'activate'));

add_action('plugins_loaded', array('Markdown_Shortcode_Plugin', 'get_instance'));

class Markdown_Shortcode_Plugin {

  private static $instance;

  const GENERATED_EXCERPT_META_KEY = '_markdown_shortcode_generated_excerpt_hash';

  public static function get_instance() {
    if (!self::$instance) {
      self::$instance = new self();
    }

    return self::$instance;
  }

  public static function activate() {
    $plugin = new self();
    $plugin->backfill_generated_excerpts();
  }

  function __construct() {
    $this->cache = array();
    add_action('init', array(&$this, 'init'));
  }

  function init() {
    add_action('wp_enqueue_scripts', array(&$this, 'init_highlight'));
    add_shortcode('markdown', array(&$this, 'markdown_shortcode'));
    add_filter('the_content', array(&$this, 'markdown_shortcode_preprocess'), 1);

    // Normal WordPress excerpt path.
    add_filter('get_the_excerpt', array(&$this, 'markdown_shortcode_excerpt'), 9, 2);

    // Builder/theme compatibility: store generated excerpt in post_excerpt.
    add_action('save_post', array(&$this, 'save_generated_excerpt'), 20, 3);
  }

  function init_highlight() {
    wp_enqueue_style("highlight", plugins_url('highlight/styles/github.css', __FILE__));
    wp_enqueue_script("highlight", plugins_url('highlight/highlight.min.js', __FILE__));
    wp_enqueue_script("highlight_init", plugins_url('init_highlight.js', __FILE__));
  }

  function markdown_shortcode($attr, $content = null) {
    if (isset($this->cache[$content])) {
      $content = $this->cache[$content];
    }

    return $this->render_markdown_shortcode_content($content);
  }

  function markdown_shortcode_pre($attr, $content = null) {
    $key = sha1($content);
    $this->cache[$key] = $content;
    return "[markdown]{$key}[/markdown]";
  }

  function markdown_shortcode_preprocess($content) {
    global $shortcode_tags;

    // Backup current registered shortcodes and clear them all out
    $orig_shortcode_tags = $shortcode_tags;
    $shortcode_tags = array();

    add_shortcode('markdown', array(&$this, 'markdown_shortcode_pre'));

    // Do the shortcode (only the one above is registered)
    $content = do_shortcode($content);

    // Put the original shortcodes back
    $shortcode_tags = $orig_shortcode_tags;
    return $content;
  }

  function markdown_shortcode_excerpt($excerpt, $post = null) {
    $post = get_post($post);

    if (!$post) {
      return $excerpt;
    }

    // Preserve stored excerpts, including manually authored ones and generated ones.
    if (trim($post->post_excerpt) !== '') {
      return $excerpt;
    }

    $generated_excerpt = $this->generate_excerpt_from_post_content($post->post_content);

    if ($generated_excerpt === '') {
      return $excerpt;
    }

    return $generated_excerpt;
  }

  function save_generated_excerpt($post_id, $post, $update) {
    if (!$post instanceof WP_Post) {
      return;
    }

    if (wp_is_post_revision($post_id) || wp_is_post_autosave($post_id)) {
      return;
    }

    if (!post_type_supports($post->post_type, 'excerpt')) {
      return;
    }

    $generated_excerpt = $this->generate_excerpt_from_post_content($post->post_content);
    $existing_excerpt = trim($post->post_excerpt);
    $existing_hash = get_post_meta($post_id, self::GENERATED_EXCERPT_META_KEY, true);
    $new_hash = $generated_excerpt !== '' ? sha1($generated_excerpt) : '';

    // No markdown excerpt available. If the existing excerpt was generated by us,
    // remove it; otherwise leave manual excerpts untouched.
    if ($generated_excerpt === '') {
      if ($existing_hash !== '') {
        $this->update_post_excerpt($post_id, '');
        delete_post_meta($post_id, self::GENERATED_EXCERPT_META_KEY);
      }

      return;
    }

    // Existing manual excerpt: do not overwrite.
    if ($existing_excerpt !== '' && $existing_hash === '') {
      return;
    }

    // Existing generated excerpt is current.
    if ($existing_excerpt !== '' && $existing_hash === $new_hash) {
      return;
    }

    $this->update_post_excerpt($post_id, $generated_excerpt);
    update_post_meta($post_id, self::GENERATED_EXCERPT_META_KEY, $new_hash);
  }

  function backfill_generated_excerpts() {
    $query = new WP_Query(array(
      'post_type'      => 'any',
      'post_status'    => array('publish', 'future', 'draft', 'pending', 'private'),
      'posts_per_page' => -1,
      'fields'         => 'ids',
      's'              => '[markdown',
    ));

    foreach ($query->posts as $post_id) {
      $post = get_post($post_id);

      if (!$post) {
        continue;
      }

      if (!post_type_supports($post->post_type, 'excerpt')) {
        continue;
      }

      // Do not overwrite manual excerpts during activation backfill.
      if (trim($post->post_excerpt) !== '') {
        continue;
      }

      $generated_excerpt = $this->generate_excerpt_from_post_content($post->post_content);

      if ($generated_excerpt === '') {
        continue;
      }

      $this->update_post_excerpt($post_id, $generated_excerpt);
      update_post_meta($post_id, self::GENERATED_EXCERPT_META_KEY, sha1($generated_excerpt));
    }
  }

  function update_post_excerpt($post_id, $excerpt) {
    remove_action('save_post', array(&$this, 'save_generated_excerpt'), 20);

    wp_update_post(array(
      'ID'           => $post_id,
      'post_excerpt' => $excerpt,
    ));

    add_action('save_post', array(&$this, 'save_generated_excerpt'), 20, 3);
  }

  function generate_excerpt_from_post_content($content) {
    $markdown_content = $this->extract_markdown_shortcode_content($content);

    if (trim($markdown_content) === '') {
      return '';
    }

    $html = $this->render_markdown_shortcode_content($markdown_content);
    $text = wp_strip_all_tags($html);
    $text = trim(preg_replace('/\s+/', ' ', $text));

    if ($text === '') {
      return '';
    }

    return wp_trim_words(
      $text,
      apply_filters('excerpt_length', 55),
      apply_filters('excerpt_more', ' [&hellip;]')
    );
  }

  function extract_markdown_shortcode_content($content) {
    if (stripos($content, '[markdown') === false) {
      return '';
    }

    $pattern = get_shortcode_regex(array('markdown'));

    if (!preg_match_all('/' . $pattern . '/s', $content, $matches)) {
      return '';
    }

    $markdown_content = array();

    foreach ($matches[2] as $index => $shortcode_name) {
      if ($shortcode_name === 'markdown' && isset($matches[5][$index])) {
        $markdown_content[] = $matches[5][$index];
      }
    }

    return trim(implode("\n\n", $markdown_content));
  }

  function render_markdown_shortcode_content($content) {
    require_once('parsedown/Parsedown.php');
    require_once('parsedown/ParsedownExtra.php');

    $content = html_entity_decode($content);
    $content = trim($content);
    $content = $this->underscores_to_spaces($content);

    $extra = new markdown_shortcode\ParsedownExtra();
    $parsed_content = '<div class="markdown">' . $extra->text($content) .'</div>';

    // Sanitize the output to prevent XSS attacks
    // wp_kses_post() removes dangerous HTML tags like <script> while keeping safe HTML
    $parsed_content = wp_kses_post($parsed_content);

    return $parsed_content;
  }

  // Replaces more than one underscore to same amount of spaces
  function underscores_to_spaces($content) {
      $content = preg_replace_callback('/_{2,}/', function ($matches) {
          return str_replace('_', ' ', $matches[0]);
      }, $content);
      return $content;
  }
}
